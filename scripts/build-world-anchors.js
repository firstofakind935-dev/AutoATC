#!/usr/bin/env node
// Writes data/worldAnchors.json (airport positions in nm on the radar's world grid) from the radar's
// worldMapAnchors.js, so the companion app measures position on exactly the grid the radar draws on.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(ROOT, 'monitor/public/365radar/src/data/worldMapAnchors.js'), 'utf8');
const wm = JSON.parse(src.trim().replace(/^export default/, '').trim().replace(/;$/, ''));
const out = {
  note: 'Airport positions on the radar world grid (nautical miles, x east, y south, origin north-west). Generated by scripts/build-world-anchors.js from monitor/public/365radar/src/data/worldMapAnchors.js - the companion measures position on this same grid so its numbers match the radar.',
  airports: {},
};
for (const [icao, a] of Object.entries(wm.anchors)) {
  out.airports[icao] = { xNm: Math.round((a.x / wm.pxPerNm) * 1000) / 1000, yNm: Math.round((a.y / wm.pxPerNm) * 1000) / 1000 };
}
fs.writeFileSync(path.join(ROOT, 'data/worldAnchors.json'), `${JSON.stringify(out, null, 1)}\n`);
console.log(`${Object.keys(out.airports).length} airports`);
